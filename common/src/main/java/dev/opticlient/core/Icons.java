    /** 패턴을 px 크기로 그린다 (x, y 는 왼쪽 위) */
    public static void draw(HudRenderer r, String[] pattern, int x, int y, int px, int color) {
        int dim = Theme.lerp(color, 0xFF000000, 0.55f);
        for (int row = 0; row < pattern.length; row++) {
            String line = pattern[row];
            int col = 0;
            while (col < line.length()) {
                char c = line.charAt(col);
                if (c == '.') {
                    col++;
                    continue;
                }
                int start = col; // 같은 글자 연속은 한 번에 칠한다
                while (col < line.length() && line.charAt(col) == c) col++;
                r.fill(x + start * px, y + row * px, x + col * px, y + (row + 1) * px, c == '+' ? dim : color);
            }
        }
    }

    public static int width(String[] pattern, int px) {
        return pattern[0].length() * px;
    }

    /** 가운데 정렬로 그리기 */
    public static void drawCentered(HudRenderer r, String[] pattern, int cx, int cy, int px, int color) {
        int w = pattern[0].length() * px;
        int h = pattern.length * px;
        draw(r, pattern, cx - w / 2, cy - h / 2, px, color);
    }
